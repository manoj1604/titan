#!/bin/bash
# Regenerates docs/cli.md from the CLI's own help text, so the reference can't drift.
# Usage: scripts/gen-cli-docs.sh [path-to-titan]   (CI fails if the result differs)
set -euo pipefail
cd "$(dirname "$0")/.."
TITAN="${1:-.build/debug/titan}"
[ -x "$TITAN" ] || swift build >/dev/null
export NO_COLOR=1 COLUMNS=100
{
  echo "# CLI reference"
  echo
  echo "<!-- Generated by scripts/gen-cli-docs.sh from \`titan help\`. Do not edit by hand. -->"
  echo
  echo '```text'
  "$TITAN" --help
  echo '```'
  # Subcommands, in help order (hidden ones aren't listed by --help).
  for cmd in $("$TITAN" --help | awk '/SUBCOMMANDS:/{on=1; next} on && /^  [a-z]/{print $1}'); do
    echo
    echo "## titan $cmd"
    echo
    echo '```text'
    "$TITAN" help "$cmd"
    echo '```'
  done
} > docs/cli.md
echo "wrote docs/cli.md ($(grep -c '^## ' docs/cli.md) commands)"
